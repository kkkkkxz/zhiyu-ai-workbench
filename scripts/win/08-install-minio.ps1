# ============================================================
# 08-install-minio.ps1
# Install MinIO server natively on Windows.
#   * download minio.exe to D:\conf\zwsk\minio
#   * create data directory
#   * write run script with access-key/secret-key env vars
#   * register a scheduled task to auto-start at logon
#   * probe ports 9000 (S3 API) / 9001 (console)
#
# Credentials must be supplied through environment variables before invoking this script.
# ============================================================
$ErrorActionPreference = 'Stop'

$Home_     = 'D:\conf\zwsk\minio'
$DataDir   = Join-Path $Home_ 'data'
$Bin       = Join-Path $Home_ 'minio.exe'
$Run       = Join-Path $Home_ 'run-minio.ps1'
$LogDir    = Join-Path $Home_ 'logs'
$DownloadUrl = 'https://dl.min.io/server/minio/release/windows-amd64/minio.exe'

$User   = if ($env:MINIO_ROOT_USER) { $env:MINIO_ROOT_USER } else { 'zwskminio' }
$Pass   = if ($env:MINIO_ROOT_PASSWORD) {
    $env:MINIO_ROOT_PASSWORD
} else {
    $secure = Read-Host 'Enter a MinIO root password' -AsSecureString
    [Runtime.InteropServices.Marshal]::PtrToStringAuto(
        [Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))
}

Write-Host "==> 1. Prepare directories" -ForegroundColor Cyan
foreach ($d in $Home_, $DataDir, $LogDir) {
    if (-not (Test-Path $d)) { New-Item -ItemType Directory -Force -Path $d | Out-Null }
}

Write-Host "==> 2. Download minio.exe" -ForegroundColor Cyan
if (Test-Path $Bin) {
    Write-Host "[SKIP] $Bin already exists ($([Math]::Round((Get-Item $Bin).Length/1MB,1)) MB)" -ForegroundColor DarkGray
} else {
    Write-Host "  fetching $DownloadUrl ..."
    $tmp = "$Bin.download"
    [Net.ServicePointManager]::SecurityProtocol = [Net.SecurityProtocolType]::Tls12
    Invoke-WebRequest -Uri $DownloadUrl -OutFile $tmp -UseBasicParsing
    Move-Item $tmp $Bin -Force
    Write-Host "[OK] minio.exe downloaded ($([Math]::Round((Get-Item $Bin).Length/1MB,1)) MB)" -ForegroundColor Green
}

Write-Host "==> 3. Write run-minio.ps1" -ForegroundColor Cyan
$runScript = @"
# Auto-generated by 08-install-minio.ps1 — do not edit manually.
`$ErrorActionPreference = 'Continue'
`$env:MINIO_ROOT_USER     = '$User'
`$env:MINIO_ROOT_PASSWORD = '$Pass'
`$logFile = '$LogDir\minio.log'
& '$Bin' server '$DataDir' --address ':9000' --console-address ':9001' *>> `$logFile
"@
$runScript | Out-File -FilePath $Run -Encoding ASCII -Force
Write-Host "[OK] $Run" -ForegroundColor Green

Write-Host "==> 4. Register scheduled task ZwskMinio (AtLogOn)" -ForegroundColor Cyan
$taskName = 'ZwskMinio'
$existing = Get-ScheduledTask -TaskName $taskName -ErrorAction SilentlyContinue
if ($existing) {
    Unregister-ScheduledTask -TaskName $taskName -Confirm:$false
    Write-Host "[INFO] removed existing task" -ForegroundColor DarkGray
}
$action  = New-ScheduledTaskAction `
    -Execute 'powershell.exe' `
    -Argument "-NoProfile -ExecutionPolicy Bypass -WindowStyle Hidden -File `"$Run`""
$trigger = New-ScheduledTaskTrigger -AtLogOn -User $env:USERNAME
$settings = New-ScheduledTaskSettingsSet -AllowStartIfOnBatteries -DontStopIfGoingOnBatteries `
    -StartWhenAvailable -RestartCount 3 -RestartInterval (New-TimeSpan -Minutes 1)
Register-ScheduledTask -TaskName $taskName -Action $action -Trigger $trigger -Settings $settings `
    -Description 'MinIO server for zwskchat' -RunLevel Limited | Out-Null
Write-Host "[OK] task '$taskName' registered" -ForegroundColor Green

Write-Host "==> 5. Start MinIO now" -ForegroundColor Cyan
$proc = Get-Process -Name 'minio' -ErrorAction SilentlyContinue
if ($proc) {
    Write-Host "[SKIP] minio.exe already running pid=$($proc.Id)" -ForegroundColor DarkGray
} else {
    Start-ScheduledTask -TaskName $taskName
    Start-Sleep -Seconds 4
}

Write-Host "==> 6. Probe ports" -ForegroundColor Cyan
function Probe($port, $label) {
    $ok = Test-NetConnection -ComputerName '127.0.0.1' -Port $port -InformationLevel Quiet -WarningAction SilentlyContinue
    if ($ok) { Write-Host "[OK]   $label 127.0.0.1:$port" -ForegroundColor Green }
    else     { Write-Warning "$label 127.0.0.1:$port not reachable yet (try again in a few seconds)" }
}
Probe 9000 'S3 API'
Probe 9001 'Console UI'

Write-Host ""
Write-Host "MinIO console: http://127.0.0.1:9001" -ForegroundColor Cyan
Write-Host "  Login user:  $User"
Write-Host "  Login pass:  $Pass"
Write-Host "Bucket auto-created on first upload (zwsk-kb)." -ForegroundColor DarkGray
